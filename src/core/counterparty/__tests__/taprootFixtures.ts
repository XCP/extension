function reverseHex(hex: string): string {
  return hex.match(/../g)!.reverse().join('');
}

/**
 * A self-consistent hostile compose built from a real one: the envelope's message is rewritten by
 * `tamper`, the commit is re-pointed at the address that envelope commits to, and the reveal is
 * re-pointed at the new commit and made to publish the new envelope. Every structural check still
 * passes, so only a check of what the message *says* can refuse it. The reveal's signature is left
 * stale — nothing the wallet checks reads it, and it cannot matter to a transaction never sent.
 */
export function tamperedTaprootCompose(fixture: TaprootFixture, tamper: (messageHex: string) => string): TaprootFixture {
  const message = fixture.data.slice(16);
  const tampered = tamper(message);
  if (tampered.length !== message.length) throw new Error('tamper must keep the length');
  const envelope = fixture.envelope_script.replace(message.slice(0, 1040), tampered.slice(0, 1040));
  const pubkey = hexToBytes(envelope.slice(-66, -2));
  const commitScript = bytesToHex(p2tr(pubkey, { script: hexToBytes(envelope) }, undefined, true).script);

  const original = Transaction.fromRaw(hexToBytes(fixture.rawtransaction), { allowUnknownOutputs: true });
  const originalScript = bytesToHex(original.getOutput(0).script!);
  const rawtransaction = fixture.rawtransaction.replace(originalScript, commitScript);
  const commitId = Transaction.fromRaw(hexToBytes(rawtransaction), { allowUnknownOutputs: true }).id;

  const signed_reveal_rawtransaction = fixture.signed_reveal_rawtransaction
    .replace(reverseHex(original.id), reverseHex(commitId))
    .replace(fixture.envelope_script, envelope);
  return { ...fixture, data: fixture.data.slice(0, 16) + tampered, envelope_script: envelope, rawtransaction, signed_reveal_rawtransaction };
}
